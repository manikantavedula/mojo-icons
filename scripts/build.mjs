#!/usr/bin/env node
// Generates the React package in src/, manifest.json and preview.html from svg/*.svg and aliases.json.
// Usage: node scripts/build.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseElements } from './lib/svgpath.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SVG_DIR = path.join(ROOT, 'svg')
const SRC = path.join(ROOT, 'src')
const ICON_DIR = path.join(SRC, 'icons')

export const toPascal = (kebab) => kebab.split('-').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('')
export const toKebab = (n) => n.replace(/([a-z])([A-Z0-9])/g, '$1-$2').replace(/([0-9])([A-Za-z])/g, '$1-$2').toLowerCase()

const aliases = JSON.parse(fs.readFileSync(path.join(ROOT, 'aliases.json'), 'utf8')).aliases
const files = fs.readdirSync(SVG_DIR).filter((f) => f.endsWith('.svg')).sort()
const icons = files.map((file) => {
  const kebab = file.replace(/\.svg$/, '')
  const svg = fs.readFileSync(path.join(SVG_DIR, file), 'utf8')
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '')
  const nodes = parseElements(inner).map(({ tag, attrs }) => [tag, attrs])
  return { name: toPascal(kebab), kebab, nodes, inner: inner.trim().replace(/\n\s*/g, '') }
})
const byName = new Map(icons.map((i) => [i.name, i]))

// alias table: alias -> canonical
const aliasOf = new Map()
for (const [alias, target] of Object.entries(aliases)) {
  if (alias.startsWith('$')) continue
  if (!byName.has(target)) {
    console.warn(`! alias ${alias} points to missing icon ${target}; skipped`)
    continue
  }
  if (byName.has(alias)) throw new Error(`Alias ${alias} collides with an icon`)
  aliasOf.set(alias, target)
}

// ---------- src/ ----------
fs.rmSync(ICON_DIR, { recursive: true, force: true })
fs.mkdirSync(ICON_DIR, { recursive: true })

const attrKey = (k) => k.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const nodeLiteral = (nodes) =>
  '[\n' +
  nodes
    .map(([tag, attrs]) => {
      const props = Object.entries(attrs).map(([k, v]) => `${/^[a-zA-Z]+$/.test(attrKey(k)) ? attrKey(k) : JSON.stringify(attrKey(k))}: ${JSON.stringify(v)}`)
      return `  [${JSON.stringify(tag)}, { ${props.join(', ')} }],`
    })
    .join('\n') +
  '\n]'

for (const icon of icons) {
  const code = `// Generated by scripts/build.mjs from svg/${icon.kebab}.svg. Do not edit.
import { createMojoIcon } from '../create-icon.js'

/** Mojo Icons: \`${icon.name}\` (svg/${icon.kebab}.svg) */
export const ${icon.name} = /* @__PURE__ */ createMojoIcon('${icon.kebab}', ${nodeLiteral(icon.nodes)})

export default ${icon.name}
`
  fs.writeFileSync(path.join(ICON_DIR, `${icon.kebab}.ts`), code)
}

const exportsList = [] // every public component export name
const lines = [
  '// Generated by scripts/build.mjs. Do not edit.',
  '// @axismojo/icons: Mojo Icons, the Axis Mojo icon set. Every export is a forwardRef React component.',
  '',
  "export { createMojoIcon } from './create-icon.js'",
  "export type { IconProps, Icon, IconNode, LucideIcon, LucideProps } from './create-icon.js'",
  '',
]
const aliasesFor = new Map()
for (const [a, t] of aliasOf) aliasesFor.set(t, [...(aliasesFor.get(t) ?? []), a])
for (const icon of icons) {
  const names = [icon.name, ...(aliasesFor.get(icon.name) ?? []).sort()]
  const all = new Set()
  for (const n of names) {
    all.add(n)
    if (!n.endsWith('Icon')) all.add(`${n}Icon`)
  }
  for (const n of all) if (byName.has(n) && n !== icon.name) all.delete(n)
  const spec = [...all].map((n) => (n === icon.name ? n : `${icon.name} as ${n}`))
  exportsList.push(...all)
  lines.push(`export { ${spec.join(', ')} } from './icons/${icon.kebab}.js'`)
}
const dup = exportsList.filter((n, i) => exportsList.indexOf(n) !== i)
if (dup.length) throw new Error(`Duplicate exports: ${dup.join(', ')}`)
fs.writeFileSync(path.join(SRC, 'index.ts'), lines.join('\n') + '\n')

// ---------- manifest.json (used by codemod.mjs and check.mjs) ----------
const manifest = {
  name: '@axismojo/icons',
  count: icons.length,
  icons: icons.map((i) => ({ name: i.name, file: `svg/${i.kebab}.svg`, aliases: aliasesFor.get(i.name) ?? [] })),
  exports: [...exportsList, 'createMojoIcon'].sort(),
  types: ['IconProps', 'Icon', 'IconNode', 'LucideIcon', 'LucideProps'],
}
fs.writeFileSync(path.join(ROOT, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')

// ---------- preview.html ----------
const data = icons.map((i) => ({ n: i.name, k: i.kebab, a: aliasesFor.get(i.name) ?? [], s: i.inner }))
const tpl = fs.readFileSync(path.join(ROOT, 'scripts', 'preview.template.html'), 'utf8')
fs.writeFileSync(path.join(ROOT, 'preview.html'), tpl.replace('/*__ICONS__*/[]', JSON.stringify(data)).replace('__COUNT__', String(icons.length)))

console.log(`Built ${icons.length} icons, ${exportsList.length} component exports (${aliasOf.size} aliases).`)
